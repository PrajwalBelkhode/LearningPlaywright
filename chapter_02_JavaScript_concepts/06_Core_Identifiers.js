// Identifier, Literal & operator

var a = 20;
a = 10;
console.log(a);

//  Identifier --> a (name which is given to the container)
// Literal --> 10 (Actual value which is being assigned)
// operator --> =

// Rule of Identifier:
// 1. Must start with a letter, underscore, or dollar sign
// 2. Can contain letters, numbers, underscores, and dollar signs
// 3. Cannot start with a number
// 4. Cannot be a reserved keyword
// 5. Cannot contain spaces
// 6. Cannot contain special characters other than underscore and dollar sign
// 7. Case sensitive

let $galaxy = "Milky way";
console.log("We are living in the",$galaxy,"galaxy.");

let _ = "Greetings!!!";
console.log(_);

let customer_new_1 = "Vijay Dikshit";
console.log(customer_new_1);

// Mathematical symbols can be used as Identifiers in JavaScript
let Ⅵ = 6;
console.log(Ⅵ);

let _३४५ = "Three hundred and forty five.";
console.log(_३४५);
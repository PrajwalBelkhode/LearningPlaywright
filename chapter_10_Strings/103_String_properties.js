// String properties and basic access

let str = "Hello, World!";
console.log(str.length); // String length - starts from 1

// Access by index

console.log(str[0]);
console.log(str[7]);
console.log(str.at(-1));
console.log(str.at(-8));

// charAt
console.log(str.charAt(4));
console.log(str.charCodeAt(9));